    public function test_only_current_active_approved_versions_produce_eligibility(): void
    {
        $this->travelTo(Carbon::parse('2026-10-29 12:00:00'));
        $admin = $this->administrator();
        $policy = $this->activePolicy('ai_service_logs', $admin);
        $log = AiServiceLog::create(['feature' => 'test', 'provider' => 'test', 'status' => 'success',
            'created_at' => '2024-01-01 12:00:00']);
        // created_at is generated by the model, not assignable through service input.
        DB::table('ai_service_logs')->where('id', $log->id)->update(['created_at' => '2024-01-01 12:00:00']);
        $log->refresh();
        $service = app(RetentionReviewService::class);
        $this->assertSame('Eligible for review', $service->assess($policy, $log)['status']);
        foreach (['provisional', 'approved'] as $status) {
            $policy->status = $status;
            $this->assertSame('Policy not active', $service->assess($policy, $log)['status']);
        }
        $policy->status = 'active';
        $policy->version = 5;
        $this->assertSame('Policy not active', $service->assess($policy, $log)['status']);
        $policy->version = 4;
        $policy->effective_from = now()->addDay()->toDateString();
        $this->assertSame('Policy not active', $service->assess($policy, $log)['status']);
        $policy->effective_from = now()->subDay()->toDateString();
        $policy->counting_rule = 'last_completed_treatment';
        $this->assertSame('Policy not active', $service->assess($policy, $log)['status']);
    }

