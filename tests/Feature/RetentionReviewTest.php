    private function activePolicy(string $category, User $admin): RetentionPolicy
    {
        $policy = RetentionPolicy::where('category', $category)->firstOrFail();
        $policy->update(['duration' => 1, 'unit' => 'years', 'counting_rule' => array_key_first($policy->countingRules()),
            'status' => 'active', 'version' => 4, 'policy_version' => 4,
            'approved_by' => $admin->id, 'approved_at' => now()->subDays(2),
            'approval_reference' => 'Clinic decision TEST-2026', 'effective_from' => now()->subDay()->toDateString(),
            'activated_by' => $admin->id, 'activated_at' => now()->subDay()]);

        return $policy->fresh();
    }

