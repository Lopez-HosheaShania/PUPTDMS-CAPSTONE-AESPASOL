    public function test_document_and_appointment_closures_track_transitions_without_using_updated_at(): void
    {
        $this->travelTo(Carbon::parse('2026-10-29 12:00:00'));
        $patient = $this->patient();
        $request = DocumentRequest::create(['patient_id' => $patient->id, 'reference_number' => 'RET-TEST-01',
            'purpose' => 'Test request', 'request_date' => now()->toDateString(), 'request_time' => '09:00:00',
            'document_type' => 'Dental Clearance', 'status' => 'pending']);
        $this->assertNull($request->fresh()->closed_at);
        $request->update(['status' => 'rejected', 'rejection_reason' => 'Test reason']);
        $this->assertSame(now()->toDateTimeString(), $request->fresh()->closed_at->toDateTimeString());
        $this->travel(1)->days();
        $request->update(['purpose' => 'A later administrative edit']);
        $this->assertSame('2026-10-29 12:00:00', $request->fresh()->closed_at->toDateTimeString());
        $request->update(['status' => 'pending']);
        $this->assertNull($request->fresh()->closed_at);

        $appointment = Appointment::create(['patient_id' => $patient->id, 'service_type' => 'Cleaning',
            'appointment_date' => now()->toDateString(), 'appointment_time' => '09:00:00', 'status' => 'upcoming']);
        $this->assertNull($appointment->closure->closed_at);
        $appointment->update(['status' => 'cancelled']);
        $this->assertSame(now()->toDateTimeString(), $appointment->fresh()->closure->closed_at->toDateTimeString());
        $originalClosure = $appointment->fresh()->closure->closed_at->toDateTimeString();
        $this->travel(1)->days();
        $appointment->update(['cancellation_reason' => 'A later administrative edit']);
        $this->assertSame($originalClosure, $appointment->fresh()->closure->closed_at->toDateTimeString());
        $appointment->update(['status' => 'rescheduled']);
        $this->assertNull($appointment->fresh()->closure->closed_at);
        $appointment->update(['appointment_date' => now()->subDay()->toDateString()]);
        Appointment::cancelElapsedScheduledAppointments();
        $this->assertNotNull($appointment->fresh()->closure->closed_at);
    }

