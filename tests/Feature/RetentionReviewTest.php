    public function test_legacy_approved_statuses_use_approval_date_and_release_does_not_restart_retention(): void
    {
        $this->travelTo(Carbon::parse('2026-10-29 12:00:00'));
        $admin = $this->administrator();
        $patient = $this->patient();
        $policy = $this->activePolicy('document_requests', $admin);
        $service = app(RetentionReviewService::class);
        foreach (['approved', 'ready', 'released'] as $status) {
            $request = DocumentRequest::create(['patient_id' => $patient->id, 'reference_number' => 'LEGACY-'.$status,
                'purpose' => 'Historical request', 'request_date' => '2024-01-01', 'request_time' => '09:00:00',
                'document_type' => 'annual_dental_clearance', 'status' => $status, 'approved_at' => '2024-01-02 10:00:00']);
            DB::table('document_request_states')->where('document_request_id', $request->id)->update(['closed_at' => now()]);
            $result = $service->assess($policy, $request->fresh());
            $this->assertSame('2024-01-02 10:00:00', $result['start']);
            $this->assertSame('2025-01-02 10:00:00', $result['due']);
            $this->assertSame('Eligible for review', $result['status']);
            $this->assertSame('approved', DocumentRequest::normalizedStatus($status));
        }
        foreach (DocumentRequest::APPROVED_STATUSES as $status) {
            $this->assertSame('approved', DocumentRequest::normalizedStatus($status));
        }
        $request = DocumentRequest::create(['patient_id' => $patient->id, 'reference_number' => 'NO-OLD-DATE',
            'purpose' => 'Imported request', 'request_date' => '2020-01-01', 'request_time' => '09:00:00',
            'document_type' => 'annual_dental_clearance', 'status' => 'released']);
        $this->assertNull($request->fresh()->closed_at);
        $this->assertSame('Needs review', $service->assess($policy, $request->fresh())['status']);
    }

