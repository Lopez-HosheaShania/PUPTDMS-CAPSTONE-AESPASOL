    public function test_approval_requires_a_configured_rule_and_an_effective_date(): void
    {
        $admin = $this->administrator();
        $policy = RetentionPolicy::where('category', 'users')->firstOrFail();
        $this->actingAs($admin);
        $payload = ['action' => 'approve', 'confirmed' => '1', 'version' => $policy->version,
            'password' => 'Password123!', 'approval_reference' => 'Approved clinic decision 2026',
            'effective_from' => now()->toDateString()];
        $this->putJson(route('admin.retention.update', $policy), $payload)->assertUnprocessable();
        $this->assertNull($policy->fresh()->approval);
        $policy->update(['counting_rule' => 'account_deactivated']);
        $invalid = $payload;
        unset($invalid['effective_from']);
        $this->putJson(route('admin.retention.update', $policy), $invalid)
            ->assertUnprocessable()->assertJsonValidationErrors('effective_from');
        $this->put(route('admin.retention.update', $policy), $payload)->assertRedirect();
        $policy->refresh();
        $this->assertSame($policy->version, $policy->policy_version);
        $this->assertSame(now()->toDateString(), $policy->effective_from->toDateString());
        $this->get(route('admin.system_settings', ['tab' => 'retention']))->assertOk()->assertSee('Activate for Review');
        $this->putJson(route('admin.retention.update', $policy), [
            'action' => 'update', 'confirmed' => '1', 'version' => $policy->version,
            'password' => 'Password123!', 'duration' => 1, 'unit' => 'years', 'counting_rule' => 'record_created',
        ])->assertUnprocessable()->assertJsonValidationErrors('counting_rule');
        $this->assertSame('approved', $policy->fresh()->status);
    }

